timestamps = re.findall(r'(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})', log)
sim_times = list(map(int, re.findall(r'Sim Time: (\d+)s', log)))

# Convert timestamps to seconds since start
times = [datetime.strptime(t, '%Y-%m-%d %H:%M:%S') for t in timestamps]
start_time = times[0]
real_time_seconds = np.array([(t - start_time).total_seconds() for t in times])
sim_times = np.array(sim_times)

# Plot 1: Normal sim time vs real time
plt.figure(figsize=(10, 5))
plt.subplot(1, 2, 1)
plt.plot(real_time_seconds, sim_times, marker='o', linestyle='-', color='blue')
plt.xlabel("Elapsed Real Time (s)")
plt.ylabel("Sim Time (s)")
plt.title("Sim Time vs Real Time")
plt.grid()

# Interpolate simulation time as a function of real time
sim_interp = interp1d(real_time_seconds, sim_times, kind='linear')

# Sample at regular real-time intervals (e.g., every 60 seconds)
interval = 60
regular_real_time = np.arange(0, real_time_seconds[-1], interval)
sim_at_regular = sim_interp(regular_real_time)

# Compute simulation time intervals between regular samples
sim_intervals = np.diff(sim_at_regular)
midpoints = (regular_real_time[1:] + regular_real_time[:-1]) / 2

# Plot 2: Interval plot
plt.subplot(1, 2, 2)
plt.plot(midpoints, sim_intervals, marker='o', linestyle='-', color='green')
plt.xlabel("Elapsed Real Time (s)")
plt.ylabel("Sim Time Interval (s)")
plt.title(f"Sim Time Interval (every {interval}s real time)")
plt.grid()

plt.tight_layout()
plt.show()
